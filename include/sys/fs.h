typedef uint64_t whence_t; ///< Seek origin type.
#define WHENCE_START ((whence_t)0) ///< Seek from the beginning of the file.
#define WHENCE_CURRENT ((whence_t)1) ///< Seek from the current position.
#define WHENCE_END ((whence_t)2) ///< Seek from the end of the file.

typedef uint64_t events_t; ///< Events type.
#define EVENTS_READ (1 << 0)  ///< File descriptor is ready to be read from.
#define EVENTS_WRITE (1 << 1) ///< File descriptor is ready to be written to.
#define EVENTS_ERROR (1 << 2) ///< File descriptor caused an error.
#define EVENTS_HUP (1 << 3)   ///< File descriptor is closed.
#define EVENTS_NVAL (1 << 4)  ///< Invalid file descriptor.

#define KEYMAX 128 ///< Maximum size of a key generated by `fdshare()`.
#define KEY128 25 ///< The size of a buffer needed to hold a 128-bit key.
#define KEY256 45 ///< The size of a buffer needed to hold a 256-bit key.
#define KEY512 89 ///< The size of a buffer needed to hold a 512-bit key.

typedef uint64_t fd_t; ///< File descriptor type.
#define FDIN ((fd_t)0)  ///< Standard input file descriptor.
#define FDOUT ((fd_t)1) ///< Standard output file descriptor.
#define FDERR ((fd_t)2) ///< Standard error file descriptor.
#define FDCWD ((fd_t)3) ///< Standard current working directory file descriptor.
#define FDNONE ((fd_t) - 1) ///< No file descriptor.

/**
 * @brief System call for sharing a file descriptor with another process.
 *
 * @param key Output buffer to store the generated key.
 * @param size The size of the output buffer.
 * @param fd The file descriptor to share.
 * @param timeout The time until the shared file descriptor expires. If `CLOCKS_NEVER`, it never expires.
 * @return An appropriate status value.
 */
static inline status_t fdshare(char* key, size_t size, fd_t fd, clock_t timeout)
{
    return syscall4(SYS_FD_SHARE, NULL, (uintptr_t)key, size, fd, timeout);
}

/**
 * @brief System call for claiming a shared file descriptor.
 *
 * After claiming a shared file descriptor, the key is no longer valid and cannot be used again.
 *
 * @param out Output pointer to store the claimed file descriptor.
 * @param key The key identifying the shared file descriptor.
 * @return An appropriate status value.
 */
static inline status_t fdclaim(fd_t* out, const char* key)
{
    return syscall1(SYS_FD_CLAIM, out, (uintptr_t)key);
}

/**
 * @brief System call for copying file descriptors.
 *
 * @param src The open file descriptor to copy.
 * @param dest Output pointer for the new file descriptor, if `FDNONE` any free file descriptor will be used,
 * otherwise the specified file descriptor will be used.
 * @return An appropriate status value.
 */
static inline status_t fdcopy(fd_t src, fd_t* dest)
{
    return syscall2(SYS_FD_COPY, dest, src, *dest);
}

typedef uint64_t file_attr_t; ///< File attribute operations.
#define FILE_GET_SIZE 0       ///< Get the size of the file.
#define FILE_SET_SIZE 1       ///< Set the size of the file.
#define FILE_GET_BLOCKS 2     ///< Get the number of blocks allocated.
#define FILE_GET_BLOCK_SIZE 3 ///< Get the block size.
#define FILE_GET_MAX_SIZE 4   ///< Get the maximum file size.
#define FILE_GET_ATIME 5      ///< Get the access time.
#define FILE_SET_ATIME 6      ///< Set the access time.
#define FILE_GET_MTIME 7      ///< Get the modification time.
#define FILE_SET_MTIME 8      ///< Set the modification time.
#define FILE_GET_CTIME 9      ///< Get the change time.
#define FILE_SET_CTIME 10     ///< Set the change time.
#define FILE_GET_BTIME 11     ///< Get the birth time.
#define FILE_SET_BTIME 12     ///< Set the birth time.
#define FILE_GET_NUM 13       ///< Get the file number.
#define FILE_GET_VOL 14       ///< Get the volume ID.
#define FILE_GET_NLINK 15     ///< Get the number of hard links.
#define FILE_GET_FLAGS 16     ///< Get the file flags.
#define FILE_SET_FLAGS 17     ///< Set the file flags.
#define FILE_GET_TYPE 18      ///< Get the file type.

typedef uint32_t file_type_t;  ///< File type operations.
#define FILE_UNKNOWN 0    ///< Unknown file type.
#define FILE_REGULAR 1    ///< Regular file.
#define FILE_DIRECTORY 3  ///< Directory.
#define FILE_SYMLINK 4    ///< Symbolic link.
#define FILE_DEVICE 5     ///< Device file.
#define FILE_SYSTEM 6     ///< System file, used for exposing kernel information to user space.
#define FILE_FILESYSTEM 7 ///< Filesystem file.

typedef uint64_t file_valid_t;   ///< Bitmask of which fields are valid within a `file_info_t` structure.
#define FILE_SIZE (1 << 0)       ///< File size is valid.
#define FILE_BLOCKS (1 << 1)     ///< Blocks allocated is valid.
#define FILE_BLOCK_SIZE (1 << 2) ///< Block size is valid.
#define FILE_MAX_SIZE (1 << 3)   ///< Maximum file size is valid.
#define FILE_ATIME (1 << 4)      ///< Access time is valid.
#define FILE_MTIME (1 << 5)      ///< Modification time is valid.
#define FILE_CTIME (1 << 6)      ///< Change time is valid.
#define FILE_BTIME (1 << 7)      ///< Birth/Creation time is valid.
#define FILE_NUM (1 << 8)        ///< File number is valid.
#define FILE_VOL (1 << 9)        ///< Volume ID is valid.
#define FILE_NLINK (1 << 10)     ///< Number of hard links is valid.
#define FILE_FLAGS (1 << 11)     ///< File flags are valid.
#define FILE_TYPE (1 << 12)      ///< File type is valid.
#define FILE_NAME (1 << 13)      ///< File name is valid.
#define FILE_MODE (1 << 14)      ///< File mode is valid.

/**
 * @brief File information structure.
 * @struct file_info_t
 */
typedef struct file_info
{
    file_valid_t valid; ///< Bitmask of which fields are valid.
    size_t size;          ///< File size in bytes.
    size_t blocks;        ///< Blocks allocated.
    size_t blockSize;     ///< Block size in bytes.
    size_t maxSize;       ///< Maximum file size.
    clock_t atime;        ///< Access time (ns).
    clock_t mtime;        ///< Modification time (ns).
    clock_t ctime;        ///< Change time (ns).
    clock_t btime;        ///< Birth/Creation time (ns).
    uint64_t num;         ///< File number, depends on the file system, for example, inode number in ext4.
    uint64_t vol;         ///< Volume ID.
    uint32_t nlink;       ///< Number of hard links.
    file_type_t type;        ///< File type.
    char name[MAX_PATH];  ///< File name.
    char mode[MAX_NAME];  ///< File mode represented by their short-hand.
    uint8_t _reserved[123];
} file_info_t;

#ifdef static_assert
static_assert(sizeof(file_info_t) == 512, "file_info_t is not 512 bytes");
#endif

